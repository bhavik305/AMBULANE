"""ESP32 + NEO-6M Telemetry Simulation and Contract Verification Test.

Validates:
1. Valid GPS fix format generated by ESP32 TinyGPSPlus is accepted by backend.
2. Invalid GPS fix (e.g. 0.0 coordinates or missing lat/lng) is rejected.
3. Speed and course formatting match ESP32 output.
4. Emergency toggle status updates.
"""

import time
from fastapi.testclient import TestClient
from main import app


def test_esp32_telemetry_flow():
    client = TestClient(app)

    with client.websocket_connect("/ws/ambulance") as ws:
        # 1. Valid GPS fix from NEO-6M parsed by ESP32
        esp32_payload = {
            "lat": 12.971598,
            "lng": 77.594562,
            "speed_kmh": 45.2,
            "heading_deg": 88.5,
            "emergency": True,
            "ts": time.time(),
        }
        ws.send_json(esp32_payload)
        ack = ws.receive_json()
        assert ack["type"] == "ack", f"Expected ack, got {ack}"

        # Check backend state
        status = client.get("/status").json()
        assert status["ambulance_connected"] is True
        st = status["ambulance_state"]
        assert abs(st["lat"] - 12.971598) < 1e-5
        assert abs(st["lng"] - 77.594562) < 1e-5
        assert st["emergency"] is True

        # 2. Invalid telemetry (missing lat/lng or corrupt string)
        invalid_payload = {
            "lat": "NOT_A_FLOAT",
            "lng": 77.594562,
            "speed_kmh": 45.2,
            "heading_deg": 88.5,
            "emergency": True,
            "ts": time.time(),
        }
        ws.send_json(invalid_payload)
        err = ws.receive_json()
        assert err["type"] == "error", f"Expected error, got {err}"

    # After disconnect, ambulance_connected is False, state persists
    status_after = client.get("/status").json()
    assert status_after["ambulance_connected"] is False
    assert status_after["ambulance_state"] is not None
    print("ESP32 simulation test PASSED successfully!")


if __name__ == "__main__":
    test_esp32_telemetry_flow()
